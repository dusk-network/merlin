//! `a94892f457202399661573480bb7250b4fe7c0af`). To regenerate them, copy this
//! test's inputs and `FixedRng` into an example in that exact upstream checkout,
//! print the resulting byte arrays, and then compare them with the literals
//! below. Generating them with this fork would only test the fork against itself.

use merlin::Transcript;
use rand_core::{CryptoRng, Error, RngCore};

struct FixedRng(u8);

impl RngCore for FixedRng {
    fn next_u32(&mut self) -> u32 {
        let mut bytes = [0; 4];
        self.fill_bytes(&mut bytes);
        u32::from_le_bytes(bytes)
    }

    fn next_u64(&mut self) -> u64 {
        let mut bytes = [0; 8];
        self.fill_bytes(&mut bytes);
        u64::from_le_bytes(bytes)
    }

    fn fill_bytes(&mut self, dest: &mut [u8]) {
        for byte in dest {
            *byte = self.0;
            self.0 = self.0.wrapping_add(1);
        }
    }

    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), Error> {
        self.fill_bytes(dest);
        Ok(())
    }
}

impl CryptoRng for FixedRng {}

